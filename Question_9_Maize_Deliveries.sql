CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade char)
RETURNS numeric(8,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade cannot be NULL'; END IF;
 CASE UPPER(p_grade)
  WHEN 'A' THEN RETURN 5.00;
  WHEN 'B' THEN RETURN 4.00;
  WHEN 'C' THEN RETURN 3.00;
  ELSE RAISE EXCEPTION 'Unsupported maize grade %',p_grade;
 END CASE;
END $$;

CREATE OR REPLACE FUNCTION trg_delivery_price_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN RAISE EXCEPTION 'Weight must be positive'; END IF;
 NEW.unit_rate:=fn_maize_rate(NEW.grade);
 NEW.total_value:=(NEW.weight_kg*NEW.unit_rate)::numeric(14,2);
 RETURN NEW;
END $$;
CREATE TRIGGER trg_delivery_price BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION trg_delivery_price_fn();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(p_farmer_id integer,p_grade char,p_weight numeric,p_date date)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN RAISE EXCEPTION 'Unknown farmer'; END IF;
 IF p_weight IS NULL OR p_weight<=0 OR p_date IS NULL THEN RAISE EXCEPTION 'Positive weight and delivery date are required'; END IF;
 -- Temporary positive values satisfy NOT NULL/CHECK; trigger replaces them using the official tariff.
 INSERT INTO deliveries(farmer_id,grade,weight_kg,unit_rate,total_value,delivered_on,is_paid)
 VALUES(p_farmer_id,UPPER(p_grade),p_weight,1,1,p_date,false);
END $$;

-- Six deliveries cover grades A/B/C and paid/unpaid states.
CALL pr_receive_delivery(1,'A',100,CURRENT_DATE-5);
CALL pr_receive_delivery(1,'B',80,CURRENT_DATE-4);
CALL pr_receive_delivery(2,'C',120,CURRENT_DATE-3);
CALL pr_receive_delivery(2,'A',60,CURRENT_DATE-2);
CALL pr_receive_delivery(3,'B',90,CURRENT_DATE-1);
CALL pr_receive_delivery(3,'C',70,CURRENT_DATE);
UPDATE deliveries SET is_paid=true WHERE delivery_id IN (1,3,5);

CREATE OR REPLACE VIEW v_farmer_amount_due AS
SELECT f.farmer_number,f.full_name,COALESCE(SUM(d.total_value) FILTER(WHERE d.is_paid=false),0)::numeric(14,2) AS amount_due
FROM farmers f LEFT JOIN deliveries d USING(farmer_id)
GROUP BY f.farmer_id,f.farmer_number,f.full_name;
SELECT * FROM v_farmer_amount_due;

CREATE INDEX idx_deliveries_farmer_date ON deliveries(farmer_id,delivered_on);
EXPLAIN SELECT delivery_id,grade,weight_kg,total_value FROM deliveries
WHERE farmer_id=1 AND delivered_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_day IS NULL THEN RAISE EXCEPTION 'Date is required'; END IF;
 INSERT INTO daily_purchases(purchase_date,total_weight,total_value)
 SELECT p_day,COALESCE(SUM(weight_kg),0),COALESCE(SUM(total_value),0)
 FROM deliveries WHERE delivered_on=p_day
 ON CONFLICT(purchase_date) DO UPDATE SET
 total_weight=EXCLUDED.total_weight,total_value=EXCLUDED.total_value;
END $$;
CALL pr_refresh_purchases(CURRENT_DATE);

